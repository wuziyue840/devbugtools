# 组合展开（导入时执行一次）
# ======================================================================

def _expand_forecasts(weather_groups, templates, objects, tails, want=500):
    """把「天气 × 句式 × 对象 × 处置」按互质步长轮转组合，去重后输出 want 条。

    返回 (天气名, 句子) 列表：天气名单独成条（卡片上做大字标题），
    句子是纯判词（不含天气名，避免和标题重复）。
    四个词料条数互质步长轮转，一个周期内的组合条条不同——这也是能凑满
    500 条不重复的关键。
    """
    weathers = tuple(w for _cat, ws in weather_groups for w in ws)
    seen = set()
    out = []
    k = 0
    limit = want * 100          # 防御：词料太小也不会死循环
    while len(out) < want and k < limit:
        weather = weathers[k % len(weathers)]
        template = templates[(k * 7) % len(templates)]
        obj = objects[(k * 11) % len(objects)]
        tail = tails[(k * 13) % len(tails)]
        text = template.format(对象=obj, 处置=tail)
        if text not in seen:
            seen.add(text)
            out.append((weather, text))
        k += 1
    return tuple(out)


def _expand_advice(yi, ji):
    """宜 × 忌 全组合，返回 ("宜：……。忌：……。", ...) 列表。"""
    return tuple(f"宜：{y}。忌：{j}。" for y in yi for j in ji)


