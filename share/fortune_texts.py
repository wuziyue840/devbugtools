# 组合展开（导入时执行一次）
# ======================================================================

def _expand_forecasts(weather_groups, templates, objects, tails):
    """把「天气 × 模板 × 对象 × 处置」组合展开并去重，返回 (天气名, 句子) 列表。

    外层按天气、内层按句式模板铺满全部组合；对象/处置按互质步长从词料里取，
    保证同一天气配到的搭配各不相同。条目数 = 天气名数 × 模板数（≥500）。
    """
    weathers = tuple(w for _cat, ws in weather_groups for w in ws)
    seen = set()
    out = []
    for w_i, weather in enumerate(weathers):
        for t_i, template in enumerate(templates):
            obj = objects[(w_i * 3 + t_i * 5) % len(objects)]
            tail = tails[(w_i * 7 + t_i * 3) % len(tails)]
            text = template.format(天气=weather, 对象=obj, 处置=tail)
            if text in seen:
                continue
            seen.add(text)
            out.append((weather, text))
    return tuple(out)


def _expand_advice(yi, ji):
    """宜 × 忌 全组合，返回 ("宜：……。忌：……。", ...) 列表。"""
    return tuple(f"宜：{y}。忌：{j}。" for y in yi for j in ji)


