# 组合抽样（导入时执行一次，固定种子 → 结果可复现）
# ======================================================================

_POOL_SEED = "八卦盘句子库固定种子"
WANT_PER_POOL = 600        # 每池条数（≥500 的要求留了余量）


def _sample_forecasts(rng, weather_groups, templates, objects, tails, want):
    """从词料里随机组合出 want 条不重复的 (天气名, 句子)。

    固定种子 → 每次导入生成的池完全一致；判词里不含天气名，
    天气名在卡片上单独做大字标题。
    """
    weathers = tuple(w for _cat, ws in weather_groups for w in ws)
    out, seen = [], set()
    guard = 0
    while len(out) < want and guard < want * 200:
        weather = rng.choice(weathers)
        template = rng.choice(templates)
        obj = rng.choice(objects)
        tail = rng.choice(tails)
        text = template.format(对象=obj, 处置=tail)
        if text not in seen:
            seen.add(text)
            out.append((weather, text))
        guard += 1
    return tuple(out)


