def dim_note(key, band, snark=False):
    """取一条维度点评；维度或档位没登记时给一句中性兜底，绝不留空。"""
    pool = (DIM_SNARK if snark else DIM_SERIOUS).get(key)
    if not pool:
        return "本维度暂无点评。"
    return pool[max(0, min(len(pool) - 1, band))]


def overall_note(grade_name, snark=False, pick=0):
    """取整卡结语；用 pick 稳定选取（同一次分析结果不变，便于截图对比）。"""
    pool = (OVERALL_SNARK if snark else OVERALL_SERIOUS).get(grade_name)
    if not pool:
        return ""
    return pool[pick % len(pool)]


def grade_short(grade_name, snark=False):
    """卡片指数旁的等级短评：毒舌版取 GRADE_SNARK，严肃版取 rules 里的短句。"""
    if snark:
        return GRADE_SNARK.get(grade_name, "")
    return health_rules.GRADE_SHORT.get(grade_name, "")